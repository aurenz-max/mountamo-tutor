// @vitest-environment jsdom
import React from 'react';
import { cleanup } from '@testing-library/react';
import { afterEach, describe, it, vi } from 'vitest';
import fixtures from './testing/workspaceFixtures.json';
import { expectClassicWorkspace, mountWithStore } from './testing/classicSurface';
import DayNightSeasons from '../primitives/visual-primitives/astronomy/DayNightSeasons';
import MoonPhasesLab from '../primitives/visual-primitives/astronomy/MoonPhasesLab';
import LifeCycleSequencer from '../primitives/visual-primitives/biology/LifeCycleSequencer';
import FoodWebBuilder from '../primitives/visual-primitives/biology/FoodWebBuilder';
import AdaptationInvestigator from '../primitives/visual-primitives/biology/AdaptationInvestigator';
import MicroscopeViewer from '../primitives/visual-primitives/biology/MicroscopeViewer';
import ProcessAnimator from '../primitives/visual-primitives/biology/ProcessAnimator';
import DnaExplorer from '../primitives/visual-primitives/biology/DnaExplorer';
import EnergyCycleEngine from '../primitives/visual-primitives/biology/EnergyCycleEngine';
import InheritanceLab from '../primitives/visual-primitives/biology/InheritanceLab';
import ProteinFolder from '../primitives/visual-primitives/biology/ProteinFolder';
import AtomBuilder from '../primitives/visual-primitives/chemistry/AtomBuilder';
import MoleculeConstructor from '../primitives/visual-primitives/chemistry/MoleculeConstructor';

const tutor = vi.hoisted(() => ({ isAudioPlaying: false, activePrimitiveId: null as string | null }));
vi.mock('../hooks/useLuminaAI', () => ({ useLuminaAI: () => ({ sendText: vi.fn(), isConnected: false, isAIResponding: false, ...tutor }) }));
vi.mock('../evaluation', () => ({
  usePrimitiveEvaluation: () => ({ submitResult: vi.fn(), hasSubmitted: false, submittedResult: null, elapsedMs: 0, resetAttempt: vi.fn() }),
  useEvaluationContext: () => null,
}));
vi.mock('../utils/SoundManager', () => ({ SoundManager: new Proxy({}, { get: () => vi.fn() }) }));
vi.mock('../components/PhaseSummaryPanel', () => ({ default: () => <div>summary</div> }));
vi.mock('../service/geminiClient-api', () => ({ generateConceptImage: vi.fn(async () => null) }));
vi.mock('@radix-ui/react-slider', () => {
  const Pass = ({ children }: { children?: React.ReactNode }) => <>{children}</>;
  return { Root: () => <input type="range" />, Track: Pass, Range: Pass, Thumb: Pass };
});
globalThis.ResizeObserver ??= class { observe() {} unobserve() {} disconnect() {} } as unknown as typeof ResizeObserver;
HTMLCanvasElement.prototype.getContext = (() => null) as unknown as typeof HTMLCanvasElement.prototype.getContext;
afterEach(() => { cleanup(); Object.assign(tutor, { isAudioPlaying: false, activePrimitiveId: null }); });

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type AnyPrimitive = React.ComponentType<{ data: any }>;
// Generated by the science helpers during the batch drives.
const SPEAKING: Array<[string, AnyPrimitive]> = [
  ['day-night-seasons', DayNightSeasons], ['moon-phases-lab', MoonPhasesLab],
  ['life-cycle-sequencer', LifeCycleSequencer],
  ['atom-builder', AtomBuilder], ['molecule-constructor', MoleculeConstructor],
];
const SILENT: Array<[string, AnyPrimitive]> = [
  // ramp-lab runs on the teaching workspace; its Pip contract is checked in RampLab.workspace.test.tsx.
  // classification-sorter, cell-builder, light-shadow-lab, constellation-builder, mixing-and-dissolving, reaction-lab, ph-explorer, gas-laws-simulator, energy-of-reactions, equation-balancer, stoichiometry-lab and telescope-simulator are workspace-only (boss families): unbound they render
  // NeedsTutor, and pip/WorkspacePip.surface.test.tsx holds their Pip contract.
  ['food-web-builder', FoodWebBuilder], ['adaptation-investigator', AdaptationInvestigator],
  ['microscope-viewer', MicroscopeViewer], ['bio-process-animator', ProcessAnimator],
  ['dna-explorer', DnaExplorer], ['energy-cycle-engine', EnergyCycleEngine],
  ['inheritance-lab', InheritanceLab],
];
// These open on a view with nothing to answer (a reading tab, a phase before the check), so no
// surface is published until the child reaches the checked part.
const OPENS_UNSCOPED: Array<[string, AnyPrimitive]> = [
  ['protein-folder', ProteinFolder],
];
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const data = (id: string): any => ({ ...(fixtures as Record<string, object>)[id], instanceId: id });

describe('science primitives share one workspace with Pip', () => {
  it.each(SPEAKING)('%s keeps the workspace contract', (id, Primitive) => {
    expectClassicWorkspace({ mounted: mountWithStore(() => <Primitive data={data(id)} />), tutor, instanceId: id });
  });

  it.each(SILENT)('%s keeps the workspace contract without tutor speech', (id, Primitive) => {
    expectClassicWorkspace({ mounted: mountWithStore(() => <Primitive data={data(id)} />), tutor, instanceId: id, silent: true });
  });

  it.each(OPENS_UNSCOPED)('%s publishes nothing before the checked part', (id, Primitive) => {
    const { store, unmount } = mountWithStore(() => <Primitive data={data(id)} />);
    if (store.getActive()) throw new Error(`${id} published a surface on its opening view`);
    unmount();
  });
});
