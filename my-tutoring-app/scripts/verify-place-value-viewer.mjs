import { JSDOM } from 'jsdom';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const html = await readFile('../artifacts/math-pedagogy-review/index.html', 'utf8');
const dom = new JSDOM(html, { runScripts: 'dangerously' });
const doc = dom.window.document;
assert.match(doc.getElementById('pvc-status').textContent, /NOT RUN/);
assert.equal(doc.querySelectorAll('details.primitive').length, 69);
const input = doc.getElementById('pvc-file');
const report = JSON.parse(await readFile(process.argv[2], 'utf8'));
await input.onchange({ target: { files: [{ text: async () => JSON.stringify(report) }] } });
assert.match(doc.getElementById('pvc-status').textContent, /BLOCKED|FAIL/);
assert.ok(doc.getElementById('pvc-results').textContent.includes(report.examples[1].hash));
await input.onchange({ target: { files: [{ text: async () => JSON.stringify({ ...report, fixture: true, time: '2020-01-01T00:00:00Z', gates: { D: 'PASS' } }) }] } });
assert.match(doc.getElementById('pvc-status').textContent, /NOT RUN \(viewer fixture\).*OLD IMPORTED RUN/);
doc.getElementById('search').value = 'place-value-chart';
doc.getElementById('search').dispatchEvent(new dom.window.Event('input'));
assert.equal(doc.querySelectorAll('details.primitive').length, 1);
await input.onchange({ target: { files: [{ text: async () => 'invalid JSON' }] } });
assert.match(doc.getElementById('pvc-status').textContent, /FAIL/);
console.log('PASS: 69 inventory cards, search preserved, real run import, hash display, old fixture cannot pass, malformed import rejected.');
dom.window.close();
