// Check a canvas spec the way the canvas author's ship checks do, with no model call. Needs Chromium.
// A spec is a folder: qa/canvas/specs/<id>/spec.json + program.tsx. Any author can write one (Gemini's saved run,
// Claude Code, a person); this script is the gate they all pass. See .claude/skills/canvas-primitive/SKILL.md.
//
// Usage:
//   node scripts/canvas-check.mjs --from=<qa/canvas run name> --id=<spec id>   start a spec folder from a saved run
//   node scripts/canvas-check.mjs --spec=<spec id>                              play every problem both ways
//   node scripts/canvas-check.mjs --spec=<spec id>                              ...on a pass, a spec with serves enters the pilot tier
//   node scripts/canvas-check.mjs --spec=<spec id> --promote                    ...and, on a pass, put it in the lesson library
//
// --spec plays each problem at rest, through its proof and through its miss, saves the three screenshots to
// specs/<id>/plays/ (plus <n>-proof-<name>.png after any step marked "shot": "<name>"), and when every problem passes writes qa/canvas/<id>.json (the tester's "Saved" list opens it).
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import * as vite from 'vite';

const arg = (name) => process.argv.find(a => a.startsWith(`--${name}=`))?.split('=').slice(1).join('=');
const root = process.cwd();
const specsDir = resolve(root, 'qa/canvas/specs');
const ID = /^[a-z0-9][a-z0-9-]{0,60}$/;

/** Regenerate a tier's index.ts from the .json entries in its folder. Returns the entry count. */
function writeIndex(dir, name, what, typeImport = '') {
  const entries = readdirSync(dir).filter(f => f.endsWith('.json')).sort().map(f => JSON.parse(readFileSync(resolve(dir, f), 'utf8')));
  const head = typeImport || 'export interface CanvasLibraryEntry { id: string; title: string; grades: string[]; summary: string; problems: number; load: () => Promise<unknown> }\n\n';
  writeFileSync(resolve(dir, 'index.ts'), `/**
 * The canvas ${name === 'CANVAS_LIBRARY' ? 'library' : 'pilot'}: ${what}
 * GENERATED by \`scripts/canvas-check.mjs\`; do not edit. This file holds only what selection reads; a program loads when
 * its canvas is served.
 */
${head}export const ${name}: CanvasLibraryEntry[] = [
${entries.map(e => `  { id: ${JSON.stringify(e.id)}, title: ${JSON.stringify(e.title)}, grades: ${JSON.stringify(e.serves.grades)}, summary: ${JSON.stringify(e.serves.summary)}, problems: ${e.problems.length}, load: () => import('./${e.id}.json').then(m => m.default) },`).join('\n')}
];
`);
  return entries.length;
}

if (arg('from')) {
  const id = arg('id');
  if (!id || !ID.test(id)) throw new Error('need --id (lowercase letters, digits, hyphens)');
  const saved = JSON.parse(readFileSync(resolve(root, 'qa/canvas', `${arg('from')}.json`), 'utf8'));
  const dir = resolve(specsDir, id);
  if (existsSync(resolve(dir, 'spec.json'))) throw new Error(`${dir} already holds a spec`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(resolve(dir, 'program.tsx'), saved.source);
  writeFileSync(resolve(dir, 'spec.json'), JSON.stringify({
    id, title: saved.title, request: saved.request, from: arg('from'), program: 'program.tsx',
    problems: [{ params: saved.params ?? {}, ask: saved.ask, goal: saved.goal, proof: saved.proof, miss: saved.miss ?? [] }],
  }, null, 2));
  console.log(`wrote ${dir}: program.tsx and spec.json with 1 problem. Add problems, then --spec=${id}`);
  process.exit(0);
}

const id = arg('spec');
if (!id || !ID.test(id)) throw new Error('need --spec=<id> or --from=<saved run> --id=<id>');
const dir = resolve(specsDir, id);
const spec = JSON.parse(readFileSync(resolve(dir, 'spec.json'), 'utf8'));
const source = readFileSync(resolve(dir, spec.program ?? 'program.tsx'), 'utf8');
if (!Array.isArray(spec.problems) || !spec.problems.length) throw new Error('the spec has no problems');

const server = await vite.createServer({ root, configFile: false, logLevel: 'error', appType: 'custom', server: { middlewareMode: true, hmr: false, ws: false, watch: null }, resolve: { alias: { '@': resolve(root, 'src'), 'server-only': resolve(root, 'vitest.stubs/server-only.ts') } } });
let failed = false;
try {
  const runner = vite.createServerModuleRunner(server.environments.ssr, { hmr: false });
  const { compileDisplay } = await runner.import('/src/components/lumina/service/gen-display/compile.ts');
  const { displayDocument } = await runner.import('/src/components/lumina/service/gen-display/document.ts');
  const { CanvasStage } = await runner.import('/src/components/lumina/service/agent-kit/canvas/stage.ts');
  const { styleNotes } = await runner.import('/src/components/lumina/service/agent-kit/canvas/canvasStyle.ts');
  const compiled = compileDisplay(source);
  if (!compiled.ok) throw new Error(`the program does not compile: ${compiled.errors.join('; ')}`);

  const blocking = [], advisories = [];
  // The shared look (canvasStyle.ts): advisory, since a canvas may need what the guide avoids.
  for (const n of styleNotes(source)) advisories.push(`style: ${n}`);
  if (!/lumina\.goal\s*\(/.test(source)) blocking.push('the program never calls lumina.goal(met)');
  // Every value a problem sets must be one the program reads; otherwise the problems are the same canvas.
  const keys = [...new Set(spec.problems.flatMap(p => Object.keys(p.params ?? {})))];
  for (const k of keys) if (!new RegExp(`params\\??\\.${k}\\b|params\\[['"]${k}['"]\\]|\\b${k}\\b[^;]*=\\s*params`).test(source)) blocking.push(`the program never reads params.${k}`);

  const stage = new CanvasStage();
  const plays = resolve(dir, 'plays');
  mkdirSync(plays, { recursive: true });
  const playLog = [], problems = [], restSeen = new Map();
  try {
    for (let i = 0; i < spec.problems.length; i++) {
      const p = spec.problems[i], n = i + 1, issues = [];
      const html = displayDocument(compiled.js, p.params ?? {});
      const proof = await stage.play(html, p.proof ?? []);
      const miss = await stage.play(html, p.miss ?? []);
      const rest = proof.rest;
      writeFileSync(resolve(plays, `${n}-rest.png`), (await stage.play(html)).png);
      writeFileSync(resolve(plays, `${n}-proof.png`), proof.png);
      writeFileSync(resolve(plays, `${n}-miss.png`), miss.png);
      for (const [kind, run] of [['proof', proof], ['miss', miss]]) {
        for (const s of run.shots ?? []) writeFileSync(resolve(plays, `${n}-${kind}-${s.name.replace(/[^a-z0-9-]/gi, '-')}.png`), s.png);
      }
      // Advisory: a long proof passes through screens nobody looks at unless some steps are marked `shot`.
      if ((p.proof ?? []).length > 6 && !(p.proof ?? []).some(s => s.shot)) advisories.push(`problem ${n}: the proof has ${p.proof.length} steps and no "shot"; mark the step that ends each phase so its screen can be read`);
      if (rest.errors.length) issues.push(`it does not run clean: ${rest.errors.slice(0, 2).join('; ')}`);
      if (rest.goal === null) issues.push('it never reports a goal');
      if (rest.goal === true) issues.push('the goal is met at rest');
      if (rest.scene == null) issues.push('it never reports a scene');
      if (!(p.proof ?? []).length) issues.push('no proof steps');
      else if (proof.stepErrors.length || proof.after.errors.length) issues.push(`the proof did not run: ${[...proof.stepErrors, ...proof.after.errors].slice(0, 2).join('; ')}`);
      else if (proof.after.goal !== true) issues.push(`the proof ends with the goal unmet (scene ${JSON.stringify(proof.after.scene).slice(0, 200)})`);
      if (!(p.miss ?? []).length) issues.push('no miss steps');
      else if (miss.stepErrors.length || miss.after.errors.length) issues.push(`the miss did not run: ${[...miss.stepErrors, ...miss.after.errors].slice(0, 2).join('; ')}`);
      else if (miss.after.goal !== false) issues.push('the wrong attempt meets the goal');
      if (!p.ask && spec.problems.length > 1) issues.push('each problem needs its own ask');
      // Two problems whose first screen and facts are the same are one problem.
      const face = JSON.stringify([rest.text, rest.scene]);
      if (restSeen.has(face)) issues.push(`its first screen is the same as problem ${restSeen.get(face)}: the params change nothing the child sees`);
      else restSeen.set(face, n);
      // Advisory: the tutor reads the scene, so a verdict or an answer in it reaches the child through the tutor.
      const verdictKeys = Object.keys(rest.scene && typeof rest.scene === 'object' ? rest.scene : {}).filter(k => /goal|met$|correct|solved|answer|success/i.test(k));
      if (verdictKeys.length) advisories.push(`problem ${n}: the scene reports ${verdictKeys.join(', ')}; the scene must hold what is on screen, never the verdict`);
      const record = (kind, run, steps) => playLog.push({ version: n, steps, restGoal: run.rest.goal, afterGoal: run.after.goal, errors: run.after.errors, stepErrors: run.stepErrors, kept: `problem ${n} ${kind}`, png: run.png.toString('base64') });
      record('proof', proof, p.proof ?? []); record('miss', miss, p.miss ?? []);
      problems.push({ params: p.params ?? {}, ask: p.ask ?? spec.ask, goal: p.goal ?? spec.goal, proof: p.proof ?? [], miss: p.miss ?? [], scene: rest.scene, proofScene: proof.after.scene, missScene: miss.after.scene });
      console.log(`problem ${n} ${JSON.stringify(p.params ?? {})}: ${issues.length ? 'FAIL' : 'pass'}${issues.map(s => `\n   - ${s}`).join('')}`);
      blocking.push(...issues.map(s => `problem ${n}: ${s}`));
    }
  } finally {
    await stage.close();
  }
  for (const a of advisories) console.log(`advisory: ${a}`);
  if (blocking.length) {
    failed = true;
    console.log(`\nBLOCKED (${blocking.length}):${blocking.map(s => `\n - ${s}`).join('')}\nscreenshots: ${plays}`);
  } else {
    const first = problems[0];
    const out = resolve(root, 'qa/canvas', `${id}.json`);
    writeFileSync(out, JSON.stringify({
      request: spec.request ?? {}, title: spec.title, ask: first.ask, goal: first.goal, html: displayDocument(compiled.js, first.params), source,
      params: first.params, proof: first.proof, miss: first.miss, scene: first.scene, proofScene: first.proofScene, missScene: first.missScene, problems,
      agentDebug: { spec: `qa/canvas/specs/${id}`, from: spec.from, advisories, plays: playLog.length, versions: problems.length, playLog },
    }, null, 2));
    console.log(`\nPASS: ${problems.length} problem(s), each played both ways. Wrote ${out}; open it in the dev panel "Canvas (agent)" saved list.\nscreenshots: ${plays}`);
    // Every passing spec with `serves` enters a lesson tier. Without --promote it is a PILOT canvas: offered only to the
    // pilot student, who plays it in a real lesson and votes (thumbs up promotes it through this script; thumbs down
    // holds it with a reason, `qa/canvas/votes.jsonl`). With --promote it enters the library every lesson can use.
    const serves = spec.serves ?? {};
    if (!Array.isArray(serves.grades) || !serves.grades.length || typeof serves.summary !== 'string' || serves.summary.length < 20) {
      if (process.argv.includes('--promote')) failed = true;
      console.log('NOT IN A LESSON TIER: spec.json needs serves: { grades: ["8"], summary: "<what the learner does and the skill it shows, one sentence>" }');
    } else {
      const lib = resolve(root, 'src/components/lumina/service/core/agent-canvas/library');
      const pilot = resolve(lib, 'pilot');
      mkdirSync(pilot, { recursive: true });
      const promote = process.argv.includes('--promote');
      const entry = `${JSON.stringify({ id, title: spec.title, serves, request: spec.request ?? {}, source, problems }, null, 1)}\n`;
      if (promote) {
        writeFileSync(resolve(lib, `${id}.json`), entry);
        if (existsSync(resolve(pilot, `${id}.json`))) rmSync(resolve(pilot, `${id}.json`));
      } else if (existsSync(resolve(lib, `${id}.json`))) {
        writeFileSync(resolve(lib, `${id}.json`), entry); // already promoted: refresh it in place
      } else {
        writeFileSync(resolve(pilot, `${id}.json`), entry);
      }
      const n = writeIndex(lib, 'CANVAS_LIBRARY', 'every canvas a lesson can be served. Each entry passed the check (every problem played\n * both ways in a browser) and was approved by the user (a play in the tester, or a thumbs up in a lesson).');
      const m = writeIndex(pilot, 'CANVAS_PILOT', 'canvases that passed the check and wait for the user\'s vote. Offered only to the pilot\n * student (`canvasCandidates.ts`); a thumbs up runs --promote, which moves the entry to the library.', "import type { CanvasLibraryEntry } from '../index';\n\n");
      console.log(promote || existsSync(resolve(lib, `${id}.json`)) ? `PROMOTED: ${id} is in the lesson library (${n} canvas(es); ${m} in the pilot).` : `PILOT: ${id} is in the pilot tier (${m} canvas(es)); a thumbs up in a lesson promotes it.`);
    }
  }
} finally {
  await server.close();
}
if (failed) process.exitCode = 1;
